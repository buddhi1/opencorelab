#!/usr/bin/env node
/* Generate feedback-backend/Form.gs from js/feedback-questions.js.
   Form.gs adds a `buildForm` function to the Apps Script project: run it once and it creates a stand-alone Google Form
   with the same consent wording, profile and survey questions as the site (useful for emailing a survey).
   Usage:  node tools/build_form.js */
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const ROOT = path.resolve(__dirname, '..');
const ctx = { window: { PDC: {} } };
vm.runInNewContext(fs.readFileSync(path.join(ROOT, 'js/feedback-questions.js'), 'utf8'), ctx);
const Q = ctx.window.PDC.FEEDBACK_QUESTIONS;

const plain = function (s) { return String(s).replace(/<[^>]+>/g, '').replace(/&amp;/g, '&'); };   // forms take plain text
const spec = {
  title: 'Open Core Lab feedback',
  description: Q.consent.intro + '\n\n' + Q.consent.points.map(function (p) { return '▶ ' + plain(p); }).join('\n'),
  ages: Q.consent.ages.map(function (a) { return a.label; }),
  profile: Q.profile,
  survey: Q.survey
};

const out = `/* GENERATED by tools/build_form.js from js/feedback-questions.js - do not edit by hand; edit the questions and rerun.
   Run buildForm once from the Apps Script editor. It creates a Google Form whose responses go to a new tab in this
   spreadsheet, and logs the form's edit and share links. 18+ answer the profile and the survey, 13-17 only the survey,
   and under-13s are sent straight to the end. */

var FORM_SPEC = ${JSON.stringify(spec, null, 2)};

function buildForm() {
  var S = FORM_SPEC;
  var form = FormApp.create(S.title).setDescription(S.description)
    .setCollectEmail(false).setAllowResponseEdits(false).setShowLinkToRespondAgain(false);
  var sheetId = PropertiesService.getScriptProperties().getProperty('SHEET_ID');
  if (sheetId) form.setDestination(FormApp.DestinationType.SPREADSHEET, sheetId);

  var age = form.addMultipleChoiceItem().setTitle('How old are you?').setRequired(true);
  var profilePage = form.addPageBreakItem().setTitle(S.profile.title).setHelpText(S.profile.intro);
  S.profile.questions.forEach(function (q) { addQuestion_(form, q); });
  var surveyPage = form.addPageBreakItem().setTitle(S.survey.title).setHelpText(S.survey.intro);
  S.survey.questions.forEach(function (q) { addQuestion_(form, q); });

  age.setChoices([
    age.createChoice(S.ages[0], profilePage),
    age.createChoice(S.ages[1], surveyPage),
    age.createChoice(S.ages[2], FormApp.PageNavigationType.SUBMIT)
  ]);
  if (form.setPublished) form.setPublished(true);
  Logger.log('Edit the form:   ' + form.getEditUrl());
  Logger.log('Share this link: ' + form.getPublishedUrl());
  return form;
}

function addQuestion_(form, q) {
  var item;
  if (q.type === 'scale') item = form.addScaleItem().setBounds(1, q.max).setLabels(q.low, q.high);
  else if (q.type === 'choice') { item = form.addMultipleChoiceItem(); item.setChoiceValues(q.options); }
  else if (q.type === 'multi') { item = form.addCheckboxItem(); item.setChoiceValues(q.options); }
  else if (q.type === 'text') item = form.addTextItem();
  else item = form.addParagraphTextItem();
  return item.setTitle(q.label).setRequired(false);
}
`;
const dest = path.join(ROOT, 'feedback-backend', 'Form.gs');
fs.writeFileSync(dest, out);
console.log('wrote ' + path.relative(ROOT, dest) + ': ' + Q.profile.questions.length + ' profile + ' + Q.survey.questions.length + ' survey questions');
