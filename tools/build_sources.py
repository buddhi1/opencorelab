#!/usr/bin/env python3
"""Bundle the course repository's teaching sources into js/sources-data.js.

The site is static, so the example source code is embedded in a single JS file
(window.PDC_SOURCES = {path: text}). Notebooks are flattened to readable Python-style
listings (markdown cells become comments).

The course code lives in a separate repo (github.com/buddhi1/pdc-class). Point the script at
a local clone of it, in this order of preference:
    python3 tools/build_sources.py /path/to/pdc-class
    COURSE_REPO=/path/to/pdc-class python3 tools/build_sources.py
    python3 tools/build_sources.py            (falls back to ../pdc-class next to this repo)
Re-run it whenever you change a source file that the site displays.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SITE = os.path.abspath(os.path.join(HERE, '..'))
OUT = os.path.join(SITE, 'js', 'sources-data.js')

INCLUDE_DIRS = ['pdc', 'hpml', 'hpml26-dataparallel_hw']
TEXT_EXT = {'.c', '.h', '.cu', '.cuh', '.cpp', '.py', '.sh', '.job', '.txt'}
TEXT_NAMES = {'Makefile', 'makefile'}
SKIP_DIR_NAMES = {'__pycache__', '.git', 'Common'}          # Common/ = large NVIDIA helper headers
SKIP_FILES = {'output-dgx.txt', 'tf_out.out', 'tf_error.err'}
MAX_BYTES = 120_000


def course_root():
    root = (sys.argv[1] if len(sys.argv) > 1 else None) or os.environ.get('COURSE_REPO') \
        or os.path.join(SITE, '..', 'pdc-class')
    root = os.path.abspath(os.path.expanduser(root))
    missing = [d for d in INCLUDE_DIRS if not os.path.isdir(os.path.join(root, d))]
    if missing:
        sys.exit('course repo not found at %s (missing %s).\n'
                 'Pass its path as an argument or set COURSE_REPO.' % (root, ', '.join(missing)))
    return root


def notebook_to_text(path):
    with open(path, encoding='utf-8') as fh:
        nb = json.load(fh)
    out = []
    for cell in nb.get('cells', []):
        src = ''.join(cell.get('source', []))
        if cell['cell_type'] == 'markdown':
            out.append('# %% [markdown]')
            out.extend('# ' + line for line in src.splitlines())
        elif cell['cell_type'] == 'code':
            if not src.strip():
                continue
            out.append('# %% [code]')
            out.append(src)
        out.append('')
    return '\n'.join(out)


def main():
    root = course_root()
    sources = {}
    for top in INCLUDE_DIRS:
        base = os.path.join(root, top)
        for dirpath, dirnames, filenames in os.walk(base):
            dirnames[:] = sorted(d for d in dirnames if d not in SKIP_DIR_NAMES)
            for fn in sorted(filenames):
                full = os.path.join(dirpath, fn)
                rel = os.path.relpath(full, root).replace(os.sep, '/')
                ext = os.path.splitext(fn)[1].lower()
                if fn in SKIP_FILES:
                    continue
                try:
                    if ext == '.ipynb':
                        text = notebook_to_text(full)
                    elif ext in TEXT_EXT or fn in TEXT_NAMES:
                        with open(full, encoding='utf-8', errors='replace') as fh:
                            text = fh.read()
                    else:
                        continue
                except (OSError, ValueError) as err:
                    print('skip', rel, err, file=sys.stderr)
                    continue
                if len(text.encode('utf-8')) > MAX_BYTES:
                    text = text[:MAX_BYTES] + '\n... (truncated in the web viewer; see the repository for the full file)\n'
                sources[rel] = text
    body = json.dumps(sources, ensure_ascii=False, indent=0, sort_keys=True)
    with open(OUT, 'w', encoding='utf-8') as fh:
        fh.write('/* GENERATED by tools/build_sources.py - do not edit by hand. */\n')
        fh.write('window.PDC_SOURCES = ' + body + ';\n')
    print('wrote %s from %s: %d files, %.0f KB' % (os.path.relpath(OUT, SITE), root, len(sources), os.path.getsize(OUT) / 1024))


if __name__ == '__main__':
    main()
